-- Esquema inicial de Ya Cayó (las cinco tablas de src/core.js) con RLS activo y grants explícitos.
-- Aditiva: solo CREATE. Requiere que el rol del servidor `ya_cayo_app` exista (sin SUPERUSER ni BYPASSRLS):
--   local: lo crea scripts/pg-test.sh · Supabase: créalo a mano con contraseña propia antes de aplicar.
-- Tiempos en segundos Unix (bigint), igual que SQLite. Ids con `by default` para conservarlos al migrar (H8).

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ya_cayo_app') THEN
    RAISE EXCEPTION 'falta el rol ya_cayo_app: créalo antes de migrar';
  END IF;
END $$;

CREATE TABLE public.ordenes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  concepto text NOT NULL,
  monto_centavos bigint NOT NULL CHECK (monto_centavos > 0),
  qr_id text UNIQUE,
  token text UNIQUE,
  qr_string text,
  qr_image text,
  pagada_en bigint,
  confirmada_en bigint,
  creada_en bigint NOT NULL,
  expira_en bigint NOT NULL,
  estado text NOT NULL DEFAULT 'pendiente' CHECK (estado IN ('pendiente','pagada','entregada'))
);

CREATE TABLE public.transacciones (
  transaction_id text PRIMARY KEY,
  orden_id bigint NOT NULL REFERENCES public.ordenes(id),
  monto_centavos bigint NOT NULL,
  date_paid bigint,
  clasificacion text NOT NULL CHECK (clasificacion IN ('valida','tardio','duplicada','invalida'))
);
CREATE INDEX transacciones_orden_id_idx ON public.transacciones(orden_id);

CREATE TABLE public.registros (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  concepto text NOT NULL,
  monto_centavos bigint NOT NULL,
  metodo text NOT NULL,
  creada_en bigint NOT NULL
);

CREATE TABLE public.eventos (
  webhook_id text PRIMARY KEY,
  recibido_en bigint NOT NULL
);

CREATE TABLE public.entregas (
  orden_id bigint PRIMARY KEY REFERENCES public.ordenes(id),
  entregada_en bigint NOT NULL
);

-- RLS + grants: nadie salvo ya_cayo_app. REVOKE explícito porque Supabase da ALL a anon/authenticated por defecto.
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['ordenes','transacciones','registros','eventos','entregas'] LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('REVOKE ALL ON public.%I FROM PUBLIC, anon, authenticated', t);
    EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON public.%I TO ya_cayo_app', t);
    EXECUTE format('CREATE POLICY servidor ON public.%I FOR ALL TO ya_cayo_app USING (true) WITH CHECK (true)', t);
  END LOOP;
END $$;

REVOKE ALL ON SEQUENCE public.ordenes_id_seq, public.registros_id_seq FROM PUBLIC, anon, authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.ordenes_id_seq, public.registros_id_seq TO ya_cayo_app;
